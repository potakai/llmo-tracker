/**
 * Google の検索（DataForSEO）の行の期限。どちらも「行を作ってから」の時間。
 *
 *   ジョブの期限（2 時間） < 回収の期限（3 時間）
 *
 * - ジョブの期限：毎朝のジョブ（serp-daily）は、行を作ってからこれを過ぎたら新しく頼む・取りに行くのをやめ、
 *   残った行を理由付きで failed にする。ふだんは 1 時間ほどで終わる（頼む・5 分 × 12 回の待ち・取りに行く）ので、
 *   Inngest のリトライで遅れても、ここまでには自分で終わる
 * - 回収の期限：recover-stale-serp（10 分ごと）は、これを過ぎてもまだ pending の行を failed にする。
 *   ジョブの期限より長くしているので、動いているジョブの行は閉じない。ジョブが取り消された・落ちたなどで、
 *   ジョブが自分で閉じられなかった行だけを拾う
 *
 * 2 つを変えるときは、この大小の関係を崩さないこと（テストで確かめている）
 */
export const SERP_JOB_DEADLINE_MINUTES = 120
export const DEFAULT_SERP_STALE_AFTER_MINUTES = 180
